"""Addresses of Gran Turismo 2 (PAL, Simulation disc SCES-12380: original, combined disc and
GT2 Plus), found with PCSX-Redux (see NOTES.md). SCES_123.80 and the race overlay of GT2.OVL are
the same at every address used here in the original game and in GT2 Plus beta 7.
"""

# SCES_123.80: PS-X EXE loaded at 0x80010000; 0x80010000..0x8005D640 is the overlay area, the
# resident code starts at the entry point
EXE = 'SCES_123.80'
OVL = 'GT2.OVL'
GAME_ENTRY = 0x8005D640
TEXT_ADDR = 0x80010000
# zeros in the overlay area of the file (0x80032238..0x8005D640): the start-up stub and the block
# go there; the stub clears the block's copy once it is in place
STUB_ADDR = 0x80050000
STUB_ROOM = 0x8005D640 - STUB_ADDR

# the resident block, in low RAM (free: zeros from 0x8000E500 in every mode), and its state
RESIDENT = 0x8000F000
STATE = 0x8000FF80

# --- resident code (SCES_123.80) -----------------------------------------------------------
# pad: the game installs its pad update (0x8007F9C0, run once per vertical blank) as a callback:
# lui $v0, 0x8008 / addiu $v0, $v0, -0x640 at 0x8007F97C; ours goes in its place and calls it
PAD_UPDATE = 0x8007F9C0
PAD_LUI, PAD_ADDIU = 0x8007F97C, 0x8007F980
PAD_LUI_WORD, PAD_ADDIU_WORD = 0x3C028008, 0x2442F9C0
PAD_BUF = 0x801F0CC8          # port 1 as libpad receives it: status, type, buttons (low = pressed)
# frame drawing: the two `jal 0x800802E0` (draws an ordering table: DMA to the GPU)
DRAW_OT = 0x800802E0
DRAW_SITES = (0x8007FF90, 0x80080D04)
DRAW_WORD = 0x0C0200B8

# --- the race overlay (GT2.OVL entry 0, loaded at 0x80010000) -------------------------------
# the lap clock (u32, 3000 per second; +60 or +120 per frame): 0x8003D154 adds to it and stores
# it with `sw $v0, ($a2)` at 0x8003D1C4, then `jr $ra`; the patch jumps to tick_store instead
CLOCK = 0x80046F44
TICK_STORE = 0x8003D1C4
TICK_WORDS = (0xACC20000, 0x03E00008)       # sw $v0, ($a2) / jr $ra
RACE_MODE = 0x801D5896        # 3 in a licence test (0x801D588C + 0x0A, read by the clock code)
MODE_LICENCE = 3

# --- GT mode --------------------------------------------------------------------------------
MONEY = 0x801D1598            # credits (u32), GT2 Plus beta 7 PAL
MONEY_MAX = 99999999


def c_header():
    names = ['GAME_ENTRY', 'RESIDENT', 'STATE', 'PAD_UPDATE', 'PAD_BUF', 'DRAW_OT', 'CLOCK',
             'RACE_MODE', 'MODE_LICENCE', 'MONEY', 'MONEY_MAX', 'PAD_LUI', 'PAD_ADDIU',
             'PAD_LUI_WORD', 'PAD_ADDIU_WORD', 'DRAW_WORD']
    # no "u" suffix: the assembler reads this header too (in C, these hex values are unsigned)
    out = ['/* generated by build.py from gt2cheat/game.py: do not edit */']
    out += ['#define %s 0x%08X' % (n, globals()[n]) for n in names]
    out.append('#define DRAW_SITE0 0x%08X' % DRAW_SITES[0])
    out.append('#define DRAW_SITE1 0x%08X' % DRAW_SITES[1])
    return '\n'.join(out) + '\n'
