"""Build the cheat: resident block + start-up stub -> gt2cheat/payload.py.

    python build.py                 compile, link, write gt2cheat/payload.py
    python build.py --list          also write the disassembly (build/*.dis)

Needs a MIPS GCC (mipsel-none-elf-* of PSn00bSDK, or mips-linux-gnu-*): on the PATH, in
tools/mips/bin, or in the directory named by the MIPS_BIN environment variable.
Only the generated gt2cheat/payload.py is needed to patch a disc (patch_disc.py).
"""
import glob
import os
import shutil
import struct
import subprocess
import sys
import zlib

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
BUILD = os.path.join(ROOT, 'build')
sys.path.insert(0, ROOT)
sys.path.insert(0, SRC)

from gt2cheat import game  # noqa: E402
import font  # noqa: E402

PAYLOAD_MAGIC = 0x43325447      # "GT2C": first word of the resident block
CFLAGS = ['-Os', '-march=r3000', '-mtune=r3000', '-mabi=32', '-mno-abicalls', '-fno-pic', '-G0',
          '-msoft-float', '-mno-check-zero-division', '-ffreestanding', '-fno-builtin', '-nostdlib',
          '-fno-common', '-Wall', '-Wextra', '-Werror']


def tool(name):
    dirs = [os.environ.get('MIPS_BIN', ''), os.path.join(ROOT, 'tools', 'mips', 'bin'),
            r'D:\DOCS\Documents\GitHub\Resident Evil 1 Hotkey\tools\mips\bin']
    for prefix in ('mipsel-none-elf-', 'mips-linux-gnu-', 'mipsel-linux-gnu-'):
        for d in dirs:
            if d:
                hits = glob.glob(os.path.join(d, prefix + name + '*'))
                if hits:
                    return hits[0]
        w = shutil.which(prefix + name)
        if w:
            return w
    sys.exit('MIPS %s not found (MIPS_BIN, tools/mips/bin or PATH)' % name)


def run(*args):
    r = subprocess.run([str(a) for a in args], capture_output=True, text=True)
    if r.returncode:
        sys.exit(' '.join(map(str, args)) + '\n' + r.stdout + r.stderr)
    return r.stdout


def symbols(elf):
    out = run(tool('nm'), elf)
    return {n: int(a, 16) & 0xFFFFFFFF for a, t, n in (l.split() for l in out.splitlines() if len(l.split()) == 3)}


def build_block(version):
    open(os.path.join(BUILD, 'font.h'), 'w', newline='\n').write(font.header())
    open(os.path.join(BUILD, 'game.h'), 'w', newline='\n').write(game.c_header())
    gcc = tool('gcc')
    defs = ['-DPAYLOAD_MAGIC=0x%08X' % PAYLOAD_MAGIC, '-DPAYLOAD_VERSION=0x%08X' % version]
    objs = []
    for src in ('start.S', 'cheat.c'):
        obj = os.path.join(BUILD, src.split('.')[0] + '.o')
        run(gcc, *CFLAGS, *defs, '-I', BUILD, '-c', os.path.join(SRC, src), '-o', obj)
        objs.append(obj)
    elf = os.path.join(BUILD, 'payload.elf')
    run(tool('ld'), '-T', os.path.join(SRC, 'payload.ld'), '-o', elf, *objs)
    und = [l for l in run(tool('nm'), '-u', elf).splitlines() if l.strip()]
    if und:
        sys.exit('undefined symbols: %s' % und)
    binf = os.path.join(BUILD, 'payload.bin')
    run(tool('objcopy'), '-O', 'binary', '-j', '.text', elf, binf)
    block = open(binf, 'rb').read()
    block += b'\0' * (-len(block) % 4)
    sym = symbols(elf)
    end = max([a for a in sym.values() if game.RESIDENT <= a < game.STATE + 0x100] + [game.RESIDENT + len(block)])
    if game.RESIDENT + len(block) > game.STATE or end > game.STATE:
        sys.exit('resident block too big: ends at %08X, state at %08X' % (max(end, game.RESIDENT + len(block)), game.STATE))
    return block, sym, elf


def build_stub(sym, block_words):
    obj = os.path.join(BUILD, 'stub.o')
    elf = os.path.join(BUILD, 'stub.elf')
    binf = os.path.join(BUILD, 'stub.bin')
    run(tool('gcc'), '-march=r3000', '-mabi=32', '-mno-abicalls', '-fno-pic', '-G0', '-c', '-I', BUILD,
        '-DBLOCK_WORDS=%d' % block_words, '-DCHEAT_BOOT=0x%08X' % sym['cheat_boot'],
        os.path.join(SRC, 'stub.S'), '-o', obj)
    run(tool('ld'), '-Ttext=0x%08X' % game.STUB_ADDR, '-e', '_start', '-o', elf, obj)
    run(tool('objcopy'), '-O', 'binary', '-j', '.text', elf, binf)
    stub = open(binf, 'rb').read()
    if symbols(elf)['block'] != game.STUB_ADDR + len(stub):
        sys.exit('stub: block label not at its end')
    return stub, elf


def write_payload_py(block, stub, sym, version):
    def hexlines(b):
        return '\n'.join("    '%s'" % b[i:i + 48].hex() for i in range(0, len(b), 48))
    out = ['"""Generated by build.py: the compiled cheat (no game data). Do not edit."""',
           '', 'VERSION = 0x%08X' % version,
           'SYMBOLS = {%s}' % ', '.join("'%s': 0x%08X" % (n, sym[n]) for n in
                                       ('cheat_boot', 'pad_hook', 'draw_hook', 'tick_store')),
           'BLOCK = bytes.fromhex(\n%s)' % hexlines(block),
           'STUB = bytes.fromhex(\n%s)' % hexlines(stub)]
    open(os.path.join(ROOT, 'gt2cheat', 'payload.py'), 'w', newline='\n').write('\n'.join(out) + '\n')


def main():
    os.makedirs(BUILD, exist_ok=True)
    block0, _, _ = build_block(0)
    version = zlib.crc32(block0) | 1
    block, sym, elf = build_block(version)
    if block[:4] + block[8:] != block0[:4] + block0[8:]:
        sys.exit('the block changed with its version word')
    stub, stub_elf = build_stub(sym, len(block) // 4)
    if len(stub) + len(block) > game.STUB_ROOM:
        sys.exit('stub + block too big for the room in SCES_123.80')
    if '--list' in sys.argv:
        for e, name in ((elf, 'payload'), (stub_elf, 'stub')):
            open(os.path.join(BUILD, name + '.dis'), 'w').write(run(tool('objdump'), '-d', e))
    write_payload_py(block, stub, sym, version)
    print('resident block %d bytes at %08X..%08X (state %08X), stub %d bytes at %08X, version %08X'
          % (len(block), game.RESIDENT, game.RESIDENT + len(block) - 1, game.STATE, len(stub),
             game.STUB_ADDR, version))
    print('cheat_boot %08X pad_hook %08X draw_hook %08X tick_store %08X'
          % tuple(sym[n] for n in ('cheat_boot', 'pad_hook', 'draw_hook', 'tick_store')))


if __name__ == '__main__':
    main()
